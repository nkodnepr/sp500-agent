"""
Валидация формата тикера — используется везде, где строка тикера в
дальнейшем участвует в построении путей к файлам (model_store.py) или
идёт в БД/внешние запросы.

ЗАЧЕМ ЭТО НУЖНО (найдено при аудите безопасности): до этого модуля
строка тикера от пользователя нигде не проверялась на допустимые
символы — она лишь приводилась к верхнему регистру и напрямую
подставлялась в Path("models_cache") / ticker в model_store.py. Без
проверки строка вроде "..\\..\\..\\AppData\\Roaming\\...\\Startup\\x"
теоретически могла бы вывести запись файлов за пределы предназначенной
папки кэша (path traversal, CWE-22). is_valid_ticker() в data_fetcher.py
косвенно отсеивал большинство таких строк (yfinance не находит по ним
данные), но полагаться только на поведение стороннего сервиса как на
защиту — ненадёжно: сегодня оно фильтрует, а как поведёт себя внешний
API завтра — не гарантировано. Явная проверка формата — самостоятельный
рубеж защиты, не зависящий от чужого сервиса.
"""
import re

# Реальные тикеры США: буквы, цифры (редко), точка или дефис для классов
# акций (BRK.B / BRK-B), длина обычно 1-5 символов, но у некоторых ETF/
# индексных продуктов бывает длиннее — 10 даёт запас с большим отрывом.
TICKER_PATTERN = re.compile(r"^[A-Z0-9][A-Z0-9.\-]{0,9}$")

# Зарезервированные имена устройств Windows — создание файла/папки с таким
# именем (даже с расширением, например CON.joblib) завершается ошибкой
# или ведёт себя непредсказуемо. Ни один реальный биржевой тикер так не
# называется, но формат-проверка выше сама по себе их не отсеивает —
# на всякий случай блокируем явно, чтобы не ловить труднообъяснимый сбой
# на Windows, если через API/тесты просочится подобная строка.
_WINDOWS_RESERVED_NAMES = {
    "CON", "PRN", "AUX", "NUL",
    *(f"COM{i}" for i in range(1, 10)),
    *(f"LPT{i}" for i in range(1, 10)),
}


def sanitize_ticker(ticker: str) -> str:
    """
    Возвращает тикер, приведённый к верхнему регистру, если он проходит
    проверку формата. Бросает ValueError на всё остальное — в том числе
    на пустые строки, пути (../, \\), пробелы внутри строки и т.д.
    """
    if not isinstance(ticker, str):
        raise ValueError(f"Тикер должен быть строкой, получено: {type(ticker)!r}")

    candidate = ticker.strip().upper()
    if not TICKER_PATTERN.match(candidate):
        raise ValueError(
            f"Некорректный формат тикера: {ticker!r}. "
            f"Ожидаются только буквы, цифры, точка и дефис, длина 1-10 символов."
        )
    if candidate in _WINDOWS_RESERVED_NAMES:
        raise ValueError(f"Тикер {ticker!r} совпадает с зарезервированным именем устройства Windows")
    return candidate


def is_safe_ticker_format(ticker: str) -> bool:
    """Булева версия sanitize_ticker — для мест, где удобнее проверка,
    а не исключение (например, ранний отсев в UI до похода в сеть)."""
    try:
        sanitize_ticker(ticker)
        return True
    except ValueError:
        return False
